'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const Town=require('../web/town-avatars.js');
const html=read('web/index.html');
const game=read('web/game.js');
const css=read('web/style.css');
test('approved forty-level Daysha atlas is wired before the live game shell',()=>{
 const avatar=html.indexOf('src="town-avatars.js"'),shell=html.indexOf('src="game.js"');
 assert.ok(avatar>0&&avatar<shell,'resolver loads before UI');
 assert.match(game,/TownAvatars=window\.RupeeTownAvatars/);
 assert.match(game,/FarmArt,TownAvatars,Kitchen/);
 assert.match(game,/function townAvatarPanel\(\)/);
 assert.match(game,/TownAvatars\.fromSave\(saved\)/);
 assert.match(game,/alt="Daysha, Town avatar /);
});
test('Town avatar actually appears in both Home and Farm, without replacing cosmetic character',()=>{
 const home=game.slice(game.indexOf('function home(){'),game.indexOf('function campaign(){'));
 const farm=game.slice(game.indexOf('function farm(){'),game.indexOf('function mine(){'));
 assert.match(home,/\+townAvatarPanel\(\)/);
 assert.match(farm,/\+townAvatarPanel\(\)/);
 assert.match(home,/cosmeticEquipped\.character/,'character wardrobe stays separate');
 assert.match(home,/cosmeticEquipped\.outfit/,'outfit wardrobe stays separate');
 assert.match(farm,/Garden\.summary\(saved\)/,'Town remains a separately leveled economy');
 assert.match(css,/\.town-avatar-art\{/,'rendered character gets portrait-size styling');
});
test('avatar progression follows campaign and does not consume independent house progression',()=>{
 const saved={unlocked:16,town:{houseLevel:5}};
 assert.equal(Town.fromSave(saved).level,16);
 saved.town.houseLevel=40;
 assert.equal(Town.fromSave(saved).level,16,'home purchases cannot advance Daysha');
 saved.unlocked=900;
 assert.equal(Town.fromSave(saved).level,40);
 assert.equal(saved.town.houseLevel,40);
 assert.match(game,/rupeerush\.save\.v1/);
});
console.log('PASS Daysha Town avatar connected to Home and Farm without progression/save changes');
