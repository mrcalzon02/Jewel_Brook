'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const Gear=require('../web/mining-gear.js'),Mine=require('../web/mining.js'),P=require('../web/progression.js');
const Farm=require('../web/town-garden.js'),Power=require('../web/mode-powerups.js'),Economy=require('../web/economy.js');
const make=()=>{const s={unlocked:1,coins:20000,gems:200,styleShards:600,stars:{}};P.migrate(s);Mine.ensure(s);Farm.ensure(s);Power.ensure(s);Economy.ensure(s);return s;};
assert.equal(Object.values(Power.CATALOG).filter(i=>i.family==='farm').length,6);
assert.equal(Object.values(Power.CATALOG).filter(i=>i.family==='mine').length,6);
assert.equal(Power.MATCH_IDS.length,16);
assert.equal(Object.keys(Power.BUNDLES).length,6);
const farm=make(),shards=farm.styleShards;
assert.equal(Power.purchase(farm,'farm-sunrise').valid,true);
assert.equal(Power.use(farm,'farm-sunrise',{plot:0},2000).valid,false);
assert.equal(Power.count(farm,'farm-sunrise'),1,'failed use must retain stock');
Farm.purchase(farm,'seed','carrot');const planted=Farm.plant(farm,0,'carrot',null,1000);
assert(planted.valid);
assert.equal(Power.use(farm,'farm-sunrise',{plot:0},2000).valid,true);
assert.equal(Farm.plotStatus(farm,0,2000).state,'ready');
Power.acquire(farm,'farm-bounty');
assert.equal(Power.use(farm,'farm-bounty',{plot:0},2000).valid,true);
assert.equal(Farm.harvest(farm,0,2000).quantity,4);
Power.acquire(farm,'farm-market');
const coinBefore=farm.coins;
assert.equal(Power.use(farm,'farm-market',{},2000).earned,57);
assert.equal(farm.coins,coinBefore+57);
assert.equal(farm.town.harvest.carrot,0);
Power.acquire(farm,'farm-seeds');
assert.equal(Power.use(farm,'farm-seeds',{crop:'wheat'},2000).valid,false,'level gate for crops');
assert.equal(Power.use(farm,'farm-seeds',{crop:'carrot'},2000).valid,true);
assert.equal(farm.town.seeds.carrot,3);
Power.acquire(farm,'farm-compost');
assert.equal(Power.use(farm,'farm-compost',{fertilizer:'compost'},2000).valid,true);
assert.equal(farm.town.fertilizers.compost,2);
const rain=make();rain.town.houseLevel=6;Farm.purchase(rain,'seed','carrot',2);
const p1=Farm.plant(rain,0,'carrot',null,1000),p2=Farm.plant(rain,1,'carrot',null,1000);
Power.acquire(rain,'farm-rainfall');
assert.equal(Power.use(rain,'farm-rainfall',{},1000).affected,2);
assert(rain.town.plots[0].readyAt<p1.readyAt&&rain.town.plots[1].readyAt<p2.readyAt);
const dig=make(),n=Mine.ensure(dig);n.strikesLeft=0;n.scansLeft=0;
Power.acquire(dig,'mine-strikes');
assert.equal(Power.use(dig,'mine-strikes',{},10000).valid,true);
assert.equal(Mine.stats(dig,10000).bonusStrikes,5);
assert.equal(Mine.excavate(dig,0,0,10000).valid,true);
assert.equal(Mine.stats(dig,10000).bonusStrikes,4);
assert.equal(Mine.stats(dig,10000).strikesLeft,0);
Power.acquire(dig,'mine-surveys');Power.use(dig,'mine-surveys',{},10000);
assert.equal(Mine.survey(dig,1,0,10000).valid,true);
assert.equal(Mine.stats(dig,10000).bonusScans,2);
Power.acquire(dig,'mine-oracle');
const scan=Mine.currentBoard(dig,10000).find(c=>!c.done&&!c.scanned);
assert.equal(Power.use(dig,'mine-oracle',{x:scan.x,y:scan.y},10000).valid,true);
assert.equal(Mine.stats(dig,10000).bonusScans,2);
Power.acquire(dig,'mine-dynamite');
const target=Mine.currentBoard(dig,10000).find(c=>!c.done);
const spare=Mine.stats(dig,10000).bonusStrikes;
assert.equal(Power.use(dig,'mine-dynamite',{x:target.x,y:target.y},10000).valid,true);
assert.equal(Mine.stats(dig,10000).bonusStrikes,spare);
Power.acquire(dig,'mine-ore');
const oldOre=Mine.stats(dig,10000).ore;
assert.equal(Power.use(dig,'mine-ore',{},10000).valid,true);
assert.equal(Mine.stats(dig,10000).ore,oldOre+5);
Power.acquire(dig,'mine-credit');
const oldCredit=dig.rupeeMine.dollars;
Power.use(dig,'mine-credit',{},10000);
assert.equal(dig.rupeeMine.dollars,oldCredit+200);
const before=dig.coins;
assert.equal(Power.buyBundle(dig,'seedling').valid,true);
assert.equal(dig.coins,before-650);
assert.equal(Power.count(dig,'farm-seeds'),2);
assert.equal(Power.buyBundle(dig,'expedition').valid,true);
assert(P.count(dig,'hammer')>=4);
assert.equal(dig.styleShards,shards,'gameplay power-ups must not spend cosmetics money');
const poor=make();poor.coins=0;
assert.equal(Power.buyBundle(poor,'seedling').valid,false);
assert.equal(Power.count(poor,'farm-seeds'),0);
assert.equal(Power.purchase(poor,'mine-strikes').valid,false);
const random=make();
for(const [roll,family] of [[.02,'farm'],[.41,'mine'],[.9,'match']]){
 const awarded=Power.grantRandom(random,()=>roll);assert.equal(awarded.valid,true);assert.equal(awarded.family,family);
}
