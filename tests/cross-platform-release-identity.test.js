'use strict';
// Release-functional identity contract: verifies update and native package wiring,
// not art style, screenshots, palettes, or cosmetic presentation.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const cmake = read('native/CMakeLists.txt');
const nativeCI = read('.github/workflows/native-desktop.yml');
const androidCI = read('.github/workflows/rupee-rush-android.yml');
const desktop = read('native/icons/rupee-rush.desktop');
const launch = read('native/icons/rupee-rush-launch.sh');
const winrc = read('native/icons/rupee-rush.rc.in');
const nativeApp = read('native/main.cpp');
const manifest = read('android/app/src/main/AndroidManifest.xml');
const gradle = read('android/app/build.gradle');
const updater = read('android/app/src/main/java/io/github/mrcalzon02/rupeerush/RupeeUpdateService.java');
const webUpdater = read('web/update.js');
const screenshotCI = read('.github/workflows/rupee-rush-android-screenshots.yml');

assert.match(cmake, /set_target_properties\(RupeeRushNative PROPERTIES OUTPUT_NAME "JewelBrookNative"\)/);
assert.match(cmake, /RENAME "jewel-brook\.png"/);
assert.match(cmake, /RENAME "jewel-brook\.desktop"/);
assert.match(cmake, /RENAME "jewel-brook-launch\.sh"/);
assert.match(nativeCI, /JewelBrook-Native-Windows-x64\.zip/);
assert.match(nativeCI, /JewelBrook-Native-Linux-x64\.tar\.gz/);
assert.match(nativeCI, /stage\/JewelBrook\/JewelBrookNative/);
assert.match(nativeCI, /jewelbrook-native-/);
assert.match(nativeCI, /--repo "\$GITHUB_REPOSITORY"/);
assert.doesNotMatch(nativeCI, /RupeeRush-Native-|RupeeRushNative|stage\/RupeeRush/);
assert.match(desktop, /Name=Jewel Brook: Heroes of Embryon/);
assert.match(desktop, /Exec=JewelBrookNative/);
assert.match(desktop, /Icon=jewel-brook/);
assert.match(launch, /exec \.\/JewelBrookNative/);
assert.match(winrc, /VERSIONINFO/);
assert.match(winrc, /ProductName", "Jewel Brook: Heroes of Embryon/);
assert.match(nativeApp, /SDL_SetAppMetadata\("Jewel Brook: Heroes of Embryon"/);
assert.match(nativeApp, /SDL_CreateWindowAndRenderer\("Jewel Brook: Heroes of Embryon"/);
assert.match(nativeApp, /SDL_GetPrefPath\("RupeeRush","RupeeRushDesktop"\)/);
assert.match(manifest, /android:label="Jewel Brook"/);
assert.match(gradle, /applicationId 'io\.github\.mrcalzon02\.rupeerush'/);
assert.match(updater, /mrcalzon02\/Jewel_Brook\/releases/);
assert.match(updater, /Jewel-Brook-Heroes-of-Embryon-Android\.apk/);
assert.match(androidCI, /Jewel Brook signed Android APK/);
assert.match(androidCI, /rupeerush-phone-test-/);
assert.match(androidCI, /Jewel-Brook-Heroes-of-Embryon-Android\.apk/);
assert.match(screenshotCI, /workflows: \["Jewel Brook signed Android APK"\]/);
assert.match(webUpdater, /mrcalzon02\/Jewel_Brook\/releases/);
assert.doesNotMatch(updater + webUpdater, /mrcalzon02\/Rupee-rush/);
console.log('PASS cross-platform package identity, launcher commands, repo destinations and save/signing preservation');
