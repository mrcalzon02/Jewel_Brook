'use strict';
const assert=require('node:assert/strict');
const E=require('../web/engine.js');
const C=require('../web/custom-levels.js');
const makeStorage=()=>{
 const map=new Map();
 return {map,getItem:k=>map.get(k)||null,setItem:(k,v)=>map.set(k,v),removeItem:k=>map.delete(k)};
};
const storage=makeStorage(),campaignKey='rupeerush.save.v1';
storage.setItem(campaignKey,JSON.stringify({unlocked:499,stars:{499:1},coins:240}));
const campaignBefore=storage.getItem(campaignKey);
const sample=C.template();
assert.equal(sample.version,1);
assert.equal(sample.width*sample.height,sample.cells.length);
assert.equal(C.unlocked({stars:{499:3}}),false,'Level 499 never unlocks player levels');
assert.equal(C.unlocked({unlocked:501,stars:{}}),false,'A forged level pointer does not unlock the editor');
assert.equal(C.unlocked({stars:{500:1}}),true,'Actual Level 500 clear unlocks editor');
assert.equal(C.unlocked(JSON.parse(JSON.stringify({stars:{500:1}}))),true,'Unlock survives save/restart');
assert.deepEqual(C.normalize(C.encode(sample)),sample,'Import/export round-trip must be lossless');
const saved=C.saveLevel(storage,C.encode(sample));
assert.deepEqual(saved,sample);
assert.deepEqual(C.loadLevel(storage,sample.id),sample);
assert.equal(C.listLevels(storage).length,1);
assert.equal(storage.getItem(campaignKey),campaignBefore,'Custom save cannot overwrite campaign progress');
const changed={...sample,title:'Revised Trial'};
C.saveLevel(storage,changed);
assert.equal(C.listLevels(storage).length,1,'Re-saving a custom ID replaces only that custom level');
assert.equal(C.loadLevel(storage,sample.id).title,'Revised Trial');
const g=C.instantiate(sample);
assert.equal(g.customLevelId,sample.id);
assert.equal(g.cfg.width,sample.width);
assert.equal(g.cfg.height,sample.height);
assert.deepEqual(g.cfg.mask,sample.mask);
assert.deepEqual(g.cfg.objectives,sample.objectives);
assert.deepEqual(g.cells.map(c=>c?c.type:null),sample.cells.map(c=>c?c.type:null));
assert.equal(E.matches(g).hit.size,0);
assert.ok(E.hasMove(g),'A saved level must be playable in the real match-three engine');
let swap=null;
for(let i=0;i<g.cells.length&&!swap;i++)for(const j of [i+1,i+g.cfg.width])
 if(E.adjacent(g,i,j)){swap=[i,j];break;}
assert.ok(swap);
const result=E.swap(g,...swap);
assert.equal(result.valid,true,'Actual game engine handles a player-level swap');
assert.equal(g.turns,1,'Playtest advances the real game engine');
assert.equal(storage.getItem(campaignKey),campaignBefore,'Playtesting does not award campaign progress');
const fail=(value,pattern)=>assert.throws(()=>C.normalize(value),pattern);
fail({...sample,version:2},/unsupported version/);
fail({...sample,id:'../../campaign'},/id must/);
fail({...sample,width:9},/width/);
fail({...sample,mask:[true]},/mask/);
fail({...sample,cells:sample.cells.slice(1)},/cells must/);
fail({...sample,cells:sample.cells.map((c,i)=>i===0?{type:999}:c)},/gem type/);
fail({...sample,cells:sample.cells.map((c,i)=>i===0?{type:E.TYPES.indexOf('peridot')}:c)},/retired gem/);
fail({...sample,objectives:[{kind:'ice',target:1}]},/starting stock/);
fail({...sample,objectives:[{kind:'collect',color:E.TYPES.indexOf('alexandrite'),target:3}]},/collection gem/);
fail({...sample,objectives:[{kind:'score',target:sample.goal+1}]},/score objective/);
fail({...sample,cells:sample.cells.map((c,i)=>i<3?{type:0}:c)},/starting board already contains/);
fail({...sample,mask:sample.mask.map((_,i)=>i<11),cells:sample.cells.map((c,i)=>i<11?c:null)},/at least 12/);
fail({...sample,cells:sample.cells.map(c=>c?{type:0}:null)},/three distinct gem/);
fail({...sample,evil:true},/unsupported field/);
fail(JSON.stringify(sample).slice(0,-4),/invalid JSON/);
const hole=structuredClone(sample);
hole.mask[0]=false;hole.cells[0]=null;
assert.deepEqual(C.normalize(C.encode(hole)).mask,hole.mask,'Irregular board mask survives save/load');
const holeGame=C.instantiate(hole);
assert.equal(holeGame.cells[0],null,'Hole remains absent in real game board');
assert.equal(holeGame.cfg.mask[0],false);
const broken=makeStorage();broken.setItem(C.KEY,'not-json');
assert.throws(()=>C.listLevels(broken),/collection is corrupt/,'Corrupt data cannot silently erase user levels');
const quota={getItem:()=>null,setItem:()=>{throw Error('quota')}};
assert.throws(()=>C.saveLevel(quota,sample),/storage is full/);
assert.equal(C.removeLevel(storage,sample.id),true);
assert.equal(C.loadLevel(storage,sample.id),null);
assert.equal(C.removeLevel(storage,sample.id),false);
assert.equal(storage.getItem(campaignKey),campaignBefore);
console.log('PASS Jewel Brook custom levels: real-engine playtest, versioned import/export, isolated persistence, unlock, invalid board rejection and recovery.');
